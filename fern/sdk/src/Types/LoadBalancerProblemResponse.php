<?php

namespace Upcloud\Types;

use Upcloud\Core\Json\JsonSerializableType;
use Upcloud\Core\Json\JsonProperty;
use Upcloud\Core\Types\ArrayType;

/**
 * Represents an error object following the Problem Details specification (RFC7807). Provides machine-readable and human-readable information about an error that occurred while processing a request.
 */
class LoadBalancerProblemResponse extends JsonSerializableType
{
    /**
     * @var string $type A URI reference identifying the problem type. When dereferenced, it typically provides human-readable documentation for the error.
     */
    #[JsonProperty('type')]
    public string $type;

    /**
     * @var string $title A short, human-readable summary of the problem type. This value should not vary between occurrences of the same error type.
     */
    #[JsonProperty('title')]
    public string $title;

    /**
     * @var ?string $detail A human-readable explanation specific to this occurrence of the problem.
     */
    #[JsonProperty('detail')]
    public ?string $detail;

    /**
     * @var int $status The HTTP status code generated by the origin server for this occurrence of the problem.
     */
    #[JsonProperty('status')]
    public int $status;

    /**
     * @var ?array<LoadBalancerProblemInvalidParamResponse> $invalidParams A list of invalid parameters that caused the problem. Used to provide detailed feedback for validation errors.
     */
    #[JsonProperty('invalid_params'), ArrayType([LoadBalancerProblemInvalidParamResponse::class])]
    public ?array $invalidParams;

    /**
     * @var ?string $correlationId A unique identifier for this error instance, useful for tracing or debugging requests.
     */
    #[JsonProperty('correlation_id')]
    public ?string $correlationId;

    /**
     * @param array{
     *   type: string,
     *   title: string,
     *   status: int,
     *   detail?: ?string,
     *   invalidParams?: ?array<LoadBalancerProblemInvalidParamResponse>,
     *   correlationId?: ?string,
     * } $values
     */
    public function __construct(
        array $values,
    ) {
        $this->type = $values['type'];
        $this->title = $values['title'];
        $this->detail = $values['detail'] ?? null;
        $this->status = $values['status'];
        $this->invalidParams = $values['invalidParams'] ?? null;
        $this->correlationId = $values['correlationId'] ?? null;
    }

    /**
     * @return string
     */
    public function __toString(): string
    {
        return $this->toJson();
    }
}
